// Generates TypeScript definitions for a game from its IL2CPP metadata, so Banans get
// IntelliSense in VS Code (the JS equivalent of Il2CppInterop's generated assemblies).
//
//   Il2Cpp.type('UnityEngine.Time')      -> Il2Cpp.Types.UnityEngine.Time$Static
//   Il2Cpp.find('UnityEngine.Camera')    -> Il2Cpp.Types.UnityEngine.Camera

import { T, FIELD, METHOD } from '../il2cpp/types.js';

const RESERVED = new Set(['break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default', 'delete', 'do', 'else', 'enum', 'export', 'extends', 'false', 'finally', 'for', 'function', 'if', 'import', 'in', 'instanceof', 'new', 'null', 'return', 'super', 'switch', 'this', 'throw', 'true', 'try', 'typeof', 'var', 'void', 'while', 'with', 'implements', 'interface', 'let', 'package', 'private', 'protected', 'public', 'static', 'yield', 'any', 'boolean', 'number', 'string', 'symbol', 'type', 'object', 'never', 'unknown', 'declare', 'namespace', 'module', 'readonly', 'keyof', 'infer', 'is', 'asserts', 'as', 'from', 'of', 'get', 'set', 'async', 'await', 'constructor', 'global', 'abstract', 'unique', 'bigint', 'undefined', 'require']);
const IDENT = /^[A-Za-z_$][\w$]*$/;
const seg = (s) => { s = s.replace(/[^\w$]/g, '_'); if (/^\d/.test(s)) s = '_' + s; return RESERVED.has(s) ? s + '_' : s; };
const key = (s) => (IDENT.test(s) && !RESERVED.has(s) ? s : JSON.stringify(s));

export class TypeGen {
  constructor(il) {
    this.il = il;
  }

  /**
   * @param {object} o
   * @param {number[]} o.images      image indices to include (types elsewhere become `any`)
   * @param {boolean} o.publicOnly   only public members
   */
  generate({ images, publicOnly = true } = {}) {
    const il = this.il;
    const md = il.md;
    const include = new Set(images || md.images.map((_, i) => i));
    this.included = new Set();
    for (let t = 0; t < md.typeCount; t++) {
      const d = md.typeDef(t);
      if (!include.has(d.image)) continue;
      if (d.name.startsWith('<') || d.name === '<Module>' || d.namespace.startsWith('<')) continue;
      if (publicOnly && !this._visible(t)) continue;
      this.included.add(t);
    }
    this.publicOnly = publicOnly;
    // Action and Action`1 live side by side in C#; in TypeScript they'd merge, so siblings that only
    // differ by generic arity keep it in their name (Action, Action_1, Action_2).
    this._names = new Map();
    const groups = new Map();
    for (const t of this.included) {
      const k = this._ns(t) + '|' + this._local(t);
      if (!groups.has(k)) groups.set(k, []);
      groups.get(k).push(t);
    }
    for (const list of groups.values()) {
      if (list.length < 2) continue;
      for (const t of list) {
        const ar = /`(\d+)$/.exec(md.typeDef(t).name);
        if (ar) this._names.set(t, this._local(t) + '_' + ar[1]);
      }
    }
    // group by namespace
    const byNs = new Map();
    for (const t of this.included) {
      const ns = this._ns(t);
      if (!byNs.has(ns)) byNs.set(ns, []);
      byNs.get(ns).push(t);
    }
    const out = [];
    out.push('// Generated by BananaLoader from the game\'s IL2CPP metadata. Do not edit.');
    out.push(`// Game: ${this.game || 'unknown'} · ${this.included.size} types · ${new Date().toISOString()}`);
    out.push('/// <reference path="./bananaloader.d.ts" />');
    out.push('');
    out.push('declare namespace Il2Cpp.Types {');
    for (const [ns, types] of [...byNs].sort((a, b) => a[0].localeCompare(b[0]))) {
      const indent = ns ? '    ' : '  ';
      if (ns) out.push(`  namespace ${ns.split('.').map(seg).join('.')} {`);
      for (const t of types.sort((a, b) => this._local(a).localeCompare(this._local(b)))) {
        try { out.push(...this._type(t).map((l) => indent + l)); } catch (e) { out.push(`${indent}// ${this._local(t)}: ${e.message}`); }
      }
      if (ns) out.push('  }');
    }
    out.push('}');
    out.push('');
    out.push('interface Il2CppTypeMap {');
    const mapped = new Set();
    for (const t of [...this.included].sort((a, b) => il.tdFullName(a).localeCompare(il.tdFullName(b)))) {
      const d = md.typeDef(t);
      if (d.isGeneric) continue;
      const fullName = il.tdFullName(t);
      if (mapped.has(fullName)) continue; // same name in two assemblies: the first one wins
      mapped.add(fullName);
      out.push(`  ${JSON.stringify(fullName)}: [${this._ref(t)}, ${this._ref(t)}$Static];`);
    }
    out.push('}');
    return out.join('\n') + '\n';
  }

  _visible(t) {
    const il = this.il;
    const d = il.md.typeDef(t);
    const vis = d.flags & 0x7; // TypeAttributes.VisibilityMask
    if (d.declaringTypeIndex < 0) return vis === 1; // Public
    if (vis !== 2) return false; // NestedPublic
    const outer = il.tdOfTypeIndex(d.declaringTypeIndex);
    return outer < 0 || this._visible(outer);
  }

  _outermost(t) {
    let x = t;
    for (let g = 0; g < 16; g++) {
      const d = this.il.md.typeDef(x);
      if (d.declaringTypeIndex < 0) return x;
      const o = this.il.tdOfTypeIndex(d.declaringTypeIndex);
      if (o < 0) return x;
      x = o;
    }
    return x;
  }

  _ns(t) { return this.il.md.typeDef(this._outermost(t)).namespace; }

  /** Name inside its namespace: Outer$Inner, generic arity removed. */
  _local(t) {
    if (this._names && this._names.has(t)) return this._names.get(t);
    const il = this.il;
    const parts = [];
    let x = t;
    for (let g = 0; g < 16; g++) {
      const d = il.md.typeDef(x);
      parts.unshift(seg(d.name.replace(/`\d+$/, '')));
      if (d.declaringTypeIndex < 0) break;
      const o = il.tdOfTypeIndex(d.declaringTypeIndex);
      if (o < 0) break;
      x = o;
    }
    return parts.join('$');
  }

  _ref(t) {
    const ns = this._ns(t);
    return 'Il2Cpp.Types.' + (ns ? ns.split('.').map(seg).join('.') + '.' : '') + this._local(t);
  }

  _genericParams(t) {
    const il = this.il;
    const d = il.md.typeDef(t);
    if (!d.isGeneric) return [];
    const names = il.md.genericParamNames(d.genericContainerIndex).map(seg);
    return names;
  }

  /** TS type for an Il2CppType*. `ctx` = generic parameter names in scope. */
  ts(p, ctx = new Set()) {
    const il = this.il;
    if (!p) return 'any';
    const t = il.typeInfo(p);
    let s;
    switch (t.kind) {
      case T.VOID: s = 'void'; break;
      case T.BOOLEAN: s = 'boolean'; break;
      case T.CHAR: case T.STRING: s = 'string'; break;
      case T.I1: case T.U1: case T.I2: case T.U2: case T.I4: case T.U4: case T.R4: case T.R8: case T.I: case T.U: case T.PTR: case T.FNPTR: s = 'number'; break;
      case T.I8: case T.U8: s = 'bigint'; break;
      case T.OBJECT: s = 'any'; break;
      case T.SZARRAY: s = `Il2CppArray<${this.ts(t.data, ctx)}>`; break;
      case T.ARRAY: s = `Il2CppArray<${this.ts(il.mem.u32At(t.data), ctx)}>`; break;
      case T.VAR: case T.MVAR: { const n = seg(il._genericParamName(t.data)); s = ctx.has(n) ? n : 'any'; break; }
      case T.VALUETYPE: case T.CLASS: {
        const td = il._tdFromData(t.data);
        if (td < 0) { s = 'any'; break; }
        const d = il.md.typeDef(td);
        if (d.isEnum) { s = 'number'; break; }
        if (!this.included.has(td)) { s = d.isValueType ? 'Record<string, any>' : 'any'; break; }
        s = this._ref(td);
        if (d.isGeneric) s += '<' + this._genericParams(td).map(() => 'any').join(', ') + '>';
        break;
      }
      case T.GENERICINST: {
        const base = il.tdOfType(p);
        if (base < 0 || !this.included.has(base)) { s = 'any'; break; }
        const args = il._genericArgs(il.mem.u32At(t.data + 4)).map((a) => this.ts(a, ctx));
        const n = this._genericParams(base).length;
        while (args.length < n) args.push('any');
        s = `${this._ref(base)}<${args.slice(0, n).join(', ')}>`;
        break;
      }
      default: s = 'any';
    }
    if (t.byref) s = `Il2CppRef<${s}>`;
    return s;
  }

  _type(t) {
    const il = this.il;
    const d = il.md.typeDef(t);
    const name = this._local(t);
    const gps = this._genericParams(t);
    const ctx = new Set(gps);
    const gdecl = gps.length ? `<${gps.map((g) => `${g} = any`).join(', ')}>` : '';
    const lines = [];
    const full = il.tdFullName(t);
    if (d.isEnum) {
      lines.push(`/** enum ${full} */`);
      lines.push(`type ${name} = number;`);
      lines.push(`interface ${name}$Static extends Il2CppTypeProxy<number> {`);
      for (const [n, v] of il.enumMembers(t)) lines.push(`  readonly ${key(n)}: ${typeof v === 'bigint' ? 'bigint' : 'number'}; // ${v}`);
      lines.push('}');
      return lines;
    }
    // base type
    let ext = 'Il2CppObject';
    const ptd = il.parentTd(t);
    if (d.isValueType) ext = '';
    else if (ptd >= 0 && this.included.has(ptd) && !(il.md.typeDef(ptd).namespace === 'System' && /^(Object|ValueType)$/.test(il.md.typeDef(ptd).name))) {
      const pp = il.typePtr(d.parentIndex);
      ext = this.ts(pp, ctx);
      if (ext === 'any') ext = 'Il2CppObject';
    }
    const inst = [];
    const stat = [];
    const sctx = new Set(); // generic parameters aren't in scope on the static side
    // properties first: an auto-property's backing field then doesn't repeat its name
    const accessorNames = new Set();
    const propLines = { inst: [], stat: [] };
    const propNames = { inst: new Set(), stat: new Set() };
    const isPublic = (m) => m && (m.flags & METHOD.ACCESS) === METHOD.PUBLIC;
    for (const p of il.propertiesOf(t)) {
      const acc = p.getter || p.setter;
      if (!acc) continue;
      // indexers (this[i]) are called as get_Item / set_Item
      if (p.getter ? p.getter.parameterCount : il.params(p.setter).length > 1) continue;
      if (p.getter) accessorNames.add(p.getter.name);
      if (p.setter) accessorNames.add(p.setter.name);
      const getter = this.publicOnly && !isPublic(p.getter) ? null : p.getter;
      const setter = this.publicOnly && !isPublic(p.setter) ? null : p.setter;
      if (!getter && !setter) continue;
      const isSt = ((getter || setter).flags & METHOD.STATIC) !== 0;
      const pc = isSt ? sctx : ctx;
      const ty = p.getter ? this.ts(il.typePtr(p.getter.returnType), pc) : this.ts(il.params(p.setter)[0].type, pc);
      const line = `${getter && !setter ? 'readonly ' : ''}${key(p.name)}: ${ty};`;
      if (isSt) { propLines.stat.push(line); propNames.stat.add(p.name); }
      else if (!d.isValueType) { propLines.inst.push(line); propNames.inst.add(p.name); } // structs arrive as plain { field } objects
    }
    // fields
    for (const f of il.fieldsOf(t)) {
      const acc = f.attrs & FIELD.ACCESS;
      if (this.publicOnly && acc !== FIELD.PUBLIC) continue;
      const fname = (/^<(.+)>k__BackingField$/.exec(f.name) || [])[1] || f.name;
      const isSt = (f.attrs & (FIELD.STATIC | FIELD.LITERAL)) !== 0;
      if (fname !== f.name && propNames[isSt ? 'stat' : 'inst'].has(fname)) continue;
      const ty = this.ts(f.type, isSt ? sctx : ctx);
      const ro = f.attrs & (FIELD.LITERAL | FIELD.INIT_ONLY) ? 'readonly ' : '';
      if (isSt) stat.push(`${ro}${key(fname)}: ${ty};`);
      else inst.push(`${ro}${key(fname)}: ${ty};`);
    }
    stat.push(...propLines.stat);
    inst.push(...propLines.inst);
    // methods (overloads grouped; generic methods get .of())
    const groups = new Map();
    for (const m of il.methodsOf(t)) {
      if (m.name === '.cctor') continue;
      if (this.publicOnly && (m.flags & METHOD.ACCESS) !== METHOD.PUBLIC) continue;
      if (accessorNames.has(m.name) && (m.flags & METHOD.SPECIAL)) continue;
      const st = m.name === '.ctor' ? 'ctor' : (m.flags & METHOD.STATIC) ? 'static' : 'inst';
      const k = st + ':' + m.name;
      if (!groups.has(k)) groups.set(k, []);
      groups.get(k).push(m);
    }
    const sig = (m, mctx) => {
      const ps = il.params(m).map((p, i) => `${seg(p.name || 'arg' + i)}: ${this.ts(p.type, mctx)}`);
      return `(${ps.join(', ')})`;
    };
    for (const [k, ms] of groups) {
      const [kind, mname] = k.split(/:(.*)/s);
      const plain = ms.filter((m) => m.genericContainerIndex === -1);
      const generic = ms.filter((m) => m.genericContainerIndex !== -1);
      if (kind === 'ctor') {
        for (const m of plain) stat.push(`$new${sig(m, sctx)}: ${name}${gps.length ? '<' + gps.map(() => 'any').join(', ') + '>' : ''};`);
        continue;
      }
      const mc = kind === 'static' ? sctx : ctx;
      const calls = plain.map((m) => `${sig(m, mc)}: ${this.ts(il.typePtr(m.returnType), mc)}`);
      let line;
      if (!generic.length) {
        line = calls.length === 1 && IDENT.test(mname) && !RESERVED.has(mname) ? `${mname}${calls[0]};` : `${key(mname)}: {\n    ${calls.map((c) => c + ';').join('\n    ')}\n  };`;
      } else {
        line = `${key(mname)}: {\n    ${[...calls.map((c) => c + ';'), '/** Generic method: .of(typeName, ...)(args) */', 'of(...typeNames: string[]): (...args: any[]) => any;'].join('\n    ')}\n  };`;
      }
      if (kind === 'static') stat.push(line);
      else if (!d.isValueType) inst.push(line);
    }
    const kindLabel = d.isInterface ? 'interface' : d.isValueType ? 'struct' : 'class';
    lines.push(`/** ${kindLabel} ${full} */`);
    if (d.isValueType) lines.push(`interface ${name}${gdecl} {`);
    else lines.push(`interface ${name}${gdecl} extends ${ext} {`);
    for (const l of inst) lines.push('  ' + l);
    lines.push('}');
    lines.push(`interface ${name}$Static extends Il2CppTypeProxy<${name}${gps.length ? '<' + gps.map(() => 'any').join(', ') + '>' : ''}> {`);
    for (const l of stat) lines.push('  ' + l);
    lines.push('}');
    return lines;
  }
}
